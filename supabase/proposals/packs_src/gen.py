from data1 import PACKS

def q(s): return "'" + s.replace("'", "''") + "'"
def arr(xs): return "ARRAY[" + ",".join(q(x) for x in xs) + "]::text[]" if xs else "'{}'::text[]"
def vars_(s):
    out=[]
    for v in re.findall(r'\{\{([^}]+)\}\}', s):
        if v not in out: out.append(v)
    return out

L=[]
L.append("""-- PromptForge Pro: bilingual (pt-PT + EN) prompt packs catalogue.
-- STATUS: PROPOSAL, NOT EXECUTED. Review packs_proposal.md, then apply with:
--   supabase db query < this file   (or paste in the SQL editor of project cwrxbxxfaemcvliasycz)
-- Idempotent: safe to re-run. Existing columns name/description/title/content/category hold the pt-PT text;
-- new *_en columns hold English. The app picks *_en when the site language is English, falling back to pt-PT.
-- Generated by /workspace/pfp/packs/gen.py.

begin;

-- 1. Schema: i18n + display fields (additive, nullable or defaulted; Admin inserts keep working)
alter table public.prompt_packs
  add column if not exists name_en text,
  add column if not exists description_en text,
  add column if not exists promise_pt text,
  add column if not exists promise_en text,
  add column if not exists audience_pt text,
  add column if not exists audience_en text,
  add column if not exists benefits_pt text[] not null default '{}',
  add column if not exists benefits_en text[] not null default '{}',
  add column if not exists outcome_category text not null default 'content',
  add column if not exists icon text,
  add column if not exists gradient text,
  add column if not exists preview_limit integer not null default 2,
  add column if not exists total_prompts integer not null default 0;

do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'prompt_packs_outcome_category_check') then
    alter table public.prompt_packs add constraint prompt_packs_outcome_category_check
      check (outcome_category in ('content','sales','productivity','creativity'));
  end if;
end $$;

alter table public.pack_prompts
  add column if not exists prompt_key text,
  add column if not exists category_key text,
  add column if not exists category_en text,
  add column if not exists title_en text,
  add column if not exists description_pt text,
  add column if not exists description_en text,
  add column if not exists content_en text,
  add column if not exists variables_pt text[] not null default '{}',
  add column if not exists variables_en text[] not null default '{}';

create unique index if not exists pack_prompts_pack_id_prompt_key_key on public.pack_prompts (pack_id, prompt_key);

comment on column public.prompt_packs.name is 'Pack name, pt-PT (default language). English in name_en.';
comment on column public.prompt_packs.description is 'Pack description, pt-PT. English in description_en.';
comment on column public.pack_prompts.title is 'Prompt title, pt-PT. English in title_en.';
comment on column public.pack_prompts.content is 'Prompt template, pt-PT, {{variables}} in variables_pt. English in content_en / variables_en.';
comment on column public.pack_prompts.category is 'Category label, pt-PT. English in category_en; stable id in category_key.';

-- 2. Merge the legacy DB-only pack 'tiktok-viral' into the canonical 'tiktok' slug used by the app
update public.prompt_packs set slug = 'tiktok'
where slug = 'tiktok-viral' and not exists (select 1 from public.prompt_packs where slug = 'tiktok');
""")

L.append("-- 3. Packs (upsert by slug)")
for p in PACKS:
    n=len(p['prompts'])
    L.append(f"""insert into public.prompt_packs (slug, name, name_en, description, description_en, promise_pt, promise_en, audience_pt, audience_en, benefits_pt, benefits_en, outcome_category, icon, gradient, is_premium, is_active, sort_order, preview_limit, total_prompts)
values ({q(p['slug'])}, {q(p['name_pt'])}, {q(p['name_en'])}, {q(p['desc_pt'])}, {q(p['desc_en'])}, {q(p['promise_pt'])}, {q(p['promise_en'])}, {q(p['aud_pt'])}, {q(p['aud_en'])}, {arr(p['ben_pt'])}, {arr(p['ben_en'])}, {q(p['outcome'])}, {q(p['icon'])}, {q(p['gradient'])}, {'true' if p['premium'] else 'false'}, true, {p['sort']}, 2, {n})
on conflict (slug) do update set name = excluded.name, name_en = excluded.name_en, description = excluded.description, description_en = excluded.description_en, promise_pt = excluded.promise_pt, promise_en = excluded.promise_en, audience_pt = excluded.audience_pt, audience_en = excluded.audience_en, benefits_pt = excluded.benefits_pt, benefits_en = excluded.benefits_en, outcome_category = excluded.outcome_category, icon = excluded.icon, gradient = excluded.gradient, is_premium = excluded.is_premium, is_active = excluded.is_active, sort_order = excluded.sort_order, preview_limit = excluded.preview_limit, total_prompts = excluded.total_prompts, updated_at = now();
""")

slugs=",".join(q(p['slug']) for p in PACKS)
keys=",".join(q(pr[0]) for p in PACKS for pr in p['prompts'])
L.append(f"""-- 4. Remove legacy/unkeyed prompts in these packs (the 12 old 'tiktok-viral' rows are rewritten below)
delete from public.pack_prompts pp using public.prompt_packs pk
where pp.pack_id = pk.id and pk.slug in ({slugs})
  and (pp.prompt_key is null or pp.prompt_key not in ({keys}));
""")
L.append("-- 5. Prompts (upsert by pack + prompt_key)")
for p in PACKS:
    L.append(f"-- {p['slug']}")
    for i,pr in enumerate(p['prompts']):
        key,ck,cpt,cen,tpt,ten,dpt,den,cpt_,cen_,free=pr
        L.append(f"""insert into public.pack_prompts (pack_id, prompt_key, category_key, category, category_en, title, title_en, description_pt, description_en, content, content_en, variables_pt, variables_en, is_free_preview, sort_order)
select id, {q(key)}, {q(ck)}, {q(cpt)}, {q(cen)}, {q(tpt)}, {q(ten)}, {q(dpt)}, {q(den)}, {q(cpt_)}, {q(cen_)}, {arr(vars_(cpt_))}, {arr(vars_(cen_))}, {'true' if free else 'false'}, {i+1} from public.prompt_packs where slug = {q(p['slug'])}
on conflict (pack_id, prompt_key) do update set category_key = excluded.category_key, category = excluded.category, category_en = excluded.category_en, title = excluded.title, title_en = excluded.title_en, description_pt = excluded.description_pt, description_en = excluded.description_en, content = excluded.content, content_en = excluded.content_en, variables_pt = excluded.variables_pt, variables_en = excluded.variables_en, is_free_preview = excluded.is_free_preview, sort_order = excluded.sort_order, updated_at = now();""")
    L.append("")
L.append("""-- 6. Keep counts honest
update public.prompt_packs pk set total_prompts = (select count(*) from public.pack_prompts pp where pp.pack_id = pk.id);

commit;
""")
open(__import__('os').path.join(__import__('os').path.dirname(__file__), '..', '20261027_packs_i18n_catalogue.sql'),'w').write("\n".join(L))
